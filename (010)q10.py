#Variáel local é uma que vai funcionar apenas em um ponto do código, exemplo:
#for i in abuble:
#O "i" do for é uma variável local pois ela só existe dentro do for.

#Agora as globais são as que são declaradas fora do escopo de um comando ou uma função, exemplo:
#varglobal = 1
#A variável "varglobal" é global pois é declarada fora de comandos.